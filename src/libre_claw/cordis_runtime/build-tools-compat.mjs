// Rebuild only the audited schema/value code, never Harness's provider stack.
import { build } from 'esbuild';
import { readFile, mkdir, writeFile, realpath } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const directory = path.dirname(fileURLToPath(import.meta.url));
const upstream = path.join(directory, 'compat/upstream');
const record = JSON.parse(await readFile(path.join(directory, 'compat/upstream.json'), 'utf8'));
for (const file of record.files) {
  const bytes = await readFile(path.join(directory, 'compat', file.file));
  if (createHash('sha256').update(bytes).digest('hex') !== file.sha256) {
    throw new Error(`Recorded Harness source changed: ${file.file}`);
  }
}
await mkdir(path.join(directory, 'vendor'), { recursive: true });
const options = {
  absWorkingDir: directory, bundle: true, platform: 'node', format: 'esm',
  // Dependencies are pinned directly in this package; their logical symlink
  // paths keep source labels stable across pnpm stores and checkout paths.
  preserveSymlinks: true,
  target: 'node22', minify: false, sourcemap: false, legalComments: 'inline',
};
await build({
  ...options,
  stdin: {
    contents: [
      "export * from './compat/upstream/schema.ts';",
      "export * from './compat/upstream/json-schema.ts';",
      "export { HarnessError } from './compat/upstream/error.ts';",
      "export { deepFreeze, snapshotJsonValue, isJsonValue } from './compat/upstream/values.ts';",
    ].join('\n'),
    resolveDir: directory,
    sourcefile: 'harness-tools-entry.mjs',
  },
  alias: {
    '@deepseek-ai/dsh-llm': path.join(upstream, 'error.ts'),
    '@deepseek-ai/dsh-util-values': path.join(upstream, 'values.ts'),
  },
  outfile: path.join(directory, 'vendor/harness-tools.mjs'),
  banner: { js: `// Generated from Harness ${record.revision}; see compat/upstream.json and compat/upstream/LICENSE.` },
});
await build({
  ...options,
  stdin: {
    contents: "export * from './compat/upstream/message.ts'; export * from './compat/upstream/assembler.ts';",
    resolveDir: directory, sourcefile: 'harness-messages-entry.mjs',
  },
  alias: {
    '@deepseek-ai/dsh-brand': path.join(upstream, 'brand.ts'),
    '@deepseek-ai/dsh-util-crypto': path.join(upstream, 'crypto.ts'),
    '@deepseek-ai/dsh-util-values': path.join(upstream, 'values.ts'),
  },
  outfile: path.join(directory, 'vendor/harness-messages.mjs'),
  banner: { js: `// Generated from Harness ${record.revision}; see compat/upstream.json and compat/upstream/LICENSE.` },
});
for (const [packageName, filename, exports] of [
  ['diff', 'diff', "export * from 'diff';"],
  ['@deepseek-ai/cosmokit', 'cosmokit', "export * from '@deepseek-ai/cosmokit';"],
  ['@deepseek-ai/schemastery', 'schemastery', "export { default } from '@deepseek-ai/schemastery'; export * from '@deepseek-ai/schemastery';"],
  ['zod', 'zod', "export * from 'zod'; export { default } from 'zod';"],
]) {
  await build({
    ...options,
    // Zod embeds whitespace-sensitive code-generation templates. Lower their
    // syntax instead of trimming template contents to satisfy Git whitespace checks.
    supported: filename === 'zod' ? { 'template-literal': false } : {},
    stdin: { contents: exports, resolveDir: directory, sourcefile: `${filename}-entry.mjs` },
    outfile: path.join(directory, `vendor/${filename}.mjs`),
    banner: { js: '// Generated by node build-tools-compat.mjs; see THIRD_PARTY_NOTICES.md.' },
  });
  await writeFile(
    path.join(directory, `vendor/${filename.toUpperCase()}-LICENSE`),
    await readFile(path.join(directory, 'node_modules', packageName, 'LICENSE')),
  );
}
await build({
  ...options, entryPoints: [path.join(upstream, 'values.ts')],
  outfile: path.join(directory, 'vendor/harness-values.mjs'),
  banner: { js: `// Generated from Harness ${record.revision}; see compat/upstream.json and compat/upstream/LICENSE.` },
});
await build({
  ...options,
  entryPoints: [path.join(directory, 'compat/ptc-typescript.mjs')],
  // Use TypeScript's browser-compatible, in-memory compiler path. Its Node
  // system host must not initialize or inspect the guest environment.
  define: { process: 'undefined' },
  // Full notices live alongside the bundle; preserve attribution in its
  // banner without reproducing whitespace-only lines from the legal header.
  legalComments: 'none',
  outfile: path.join(directory, 'vendor/ptc-typescript.mjs'),
  banner: { js: '// Copyright (c) Microsoft Corporation. All rights reserved.\n// Microsoft TypeScript 5.9.3 transpileModule wrapper. See THIRD_PARTY_NOTICES.md.' },
});
for (const [source, target] of [['LICENSE.txt', 'TYPESCRIPT-LICENSE'], ['ThirdPartyNoticeText.txt', 'TYPESCRIPT-THIRD-PARTY-NOTICES']]) {
  const notice = await readFile(path.join(directory, 'node_modules/typescript', source), 'utf8');
  await writeFile(path.join(directory, 'vendor', target), notice.replace(/\r\n/g, '\n').replace(/[ \t]+$/gm, '').trimEnd() + '\n');
}
await build({
  ...options,
  stdin: { contents: "export { default as React } from 'react'; export * as jsxRuntime from 'react/jsx-runtime'; export { default as Reconciler } from 'react-reconciler'; export * as ReconcilerConstants from 'react-reconciler/constants.js';",
    resolveDir: directory, sourcefile: 'client-react-entry.mjs' },
  define: { 'process.env.NODE_ENV': '"production"' },
  outfile: path.join(directory, 'vendor/client-react.mjs'),
  banner: { js: '// React 18.3.1 and react-reconciler 0.29.2. See THIRD_PARTY_NOTICES.md.' },
});
const licensed = new Set();
async function clientLicense(name, locate = createRequire(import.meta.url)) {
  if (licensed.has(name)) return;
  licensed.add(name);
  const manifest = await realpath(locate.resolve(`${name}/package.json`));
  await writeFile(path.join(directory, `vendor/${name.toUpperCase()}-LICENSE`), await readFile(path.join(path.dirname(manifest), 'LICENSE')));
  for (const dependency of Object.keys(JSON.parse(await readFile(manifest, 'utf8')).dependencies ?? {})) {
    await clientLicense(dependency, createRequire(manifest));
  }
}
await clientLicense('react');
await clientLicense('react-reconciler');
